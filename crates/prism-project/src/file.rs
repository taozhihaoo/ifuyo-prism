//! 文件模型与分类。
//!
//! FileKind（分类）与 Language（语言）是两个正交概念：
//! `package.json` 是 JSON 语言 + Config 类型；`foo.test.ts` 是 TypeScript + Test。
//! 分类必须携带 confidence 与 reason（纲领：可解释）。

use crate::configuration::known_configuration;
use crate::language::{Language, LanguageRegistry};
use prism_core::ids::FileId;
use prism_core::timestamp::Timestamp;
use prism_core::{Confidence, PrismResult};
use serde::{Deserialize, Serialize};
use std::path::Path;

/// 文件角色分类（JSON 为 snake_case 字符串）。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum FileKind {
    Source,
    Test,
    Config,
    Documentation,
    Asset,
    Generated,
    Binary,
    Unknown,
}

/// 分类的完整事实：kind + confidence + reason。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FileClassification {
    pub kind: FileKind,
    pub confidence: Confidence,
    pub reason: String,
}

/// 一个被发现的文件（只含 metadata，不含内容）。
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FileInfo {
    /// 确定性 ID：`file:{relative_path}`。
    pub id: FileId,
    /// 项目相对路径，`/` 分隔（文件的业务身份，纲领 §11 路径规则）。
    pub relative_path: String,
    pub file_name: String,
    /// 小写扩展名（不含点）；无扩展名为 None。
    pub extension: Option<String>,
    pub size_bytes: u64,
    pub language: Option<Language>,
    pub classification: FileClassification,
    /// 是否可被后续阶段（M2 parser 等）分析。
    pub analyzable: bool,
    /// 不可分析的原因（如 "too_large" / "binary" / "symlink"）。
    pub non_analyzable_reason: Option<String>,
    pub modified_at: Option<Timestamp>,
    pub is_hidden: bool,
    pub is_symlink: bool,
}

/// 内容型二进制（只记录 metadata，不读取内容；纲领 §58/§32）。
const BINARY_EXTENSIONS: &[&str] = &[
    "exe", "dll", "so", "dylib", "a", "lib", "o", "obj", "pdb", "wasm", "class", "jar", "war",
    "zip", "tar", "gz", "tgz", "bz2", "xz", "7z", "rar", "iso", "img", "sqlite", "sqlite3", "db",
    "db3", "mdb", "accdb",
];

/// 媒体/图片/字体资产。
const ASSET_EXTENSIONS: &[&str] = &[
    "png", "jpg", "jpeg", "gif", "webp", "bmp", "ico", "icns", "svg", "tif", "tiff", "avif", "mp4",
    "mov", "avi", "mkv", "webm", "mp3", "wav", "flac", "ogg", "m4a", "woff", "woff2", "ttf", "otf",
    "eot",
];

/// 配置风格的扩展名（未命中已知名时的保守兜底，Low confidence）。
const CONFIG_STYLE_EXTENSIONS: &[&str] = &[
    "toml",
    "yaml",
    "yml",
    "json",
    "json5",
    "jsonc",
    "ini",
    "cfg",
    "conf",
    "properties",
    "xml",
];

/// 文档扩展名。
const DOCUMENTATION_EXTENSIONS: &[&str] = &["md", "markdown", "rst", "adoc", "txt"];

/// 已知文档文件名（大小写不敏感）。
const DOCUMENTATION_NAMES: &[&str] = &[
    "license",
    "changelog",
    "notice",
    "authors",
    "contributing",
    "code_of_conduct",
];

/// 测试目录段（纲领 §23）。
const TEST_DIRECTORY_SEGMENTS: &[&str] = &["test", "tests", "__tests__"];

/// 生成内容目录段（纲领 §22）。
const GENERATED_DIRECTORY_SEGMENTS: &[&str] = &[
    "generated",
    "__generated__",
    "autogenerated",
    "dist",
    "build",
    "coverage",
];

/// 文件分类器。
#[derive(Debug, Clone)]
pub struct FileClassifier {
    registry: LanguageRegistry,
}

impl FileClassifier {
    pub fn new() -> Self {
        FileClassifier {
            registry: LanguageRegistry::with_defaults(),
        }
    }

    pub fn registry(&self) -> &LanguageRegistry {
        &self.registry
    }

    /// 从文件名检测语言。
    pub fn detect_language(&self, file_name: &str) -> Option<Language> {
        self.registry.detect(file_name)
    }

    /// 完整分类评估：kind + 是否可分析 + 原因。
    /// （大小上限的 too_large 判定在 [`build_file_info`] 中统一处理。）
    pub fn assess(
        &self,
        relative_path: &str,
        file_name: &str,
        is_symlink: bool,
    ) -> (FileClassification, bool, Option<String>) {
        if is_symlink {
            return (
                FileClassification {
                    kind: FileKind::Unknown,
                    confidence: Confidence::Low,
                    reason: "symlink entry (not followed)".to_string(),
                },
                false,
                Some("symlink".to_string()),
            );
        }

        let extension = Path::new(file_name)
            .extension()
            .map(|e| e.to_string_lossy().to_ascii_lowercase());
        let lower_name = file_name.to_ascii_lowercase();

        // 1) 二进制 / 资产：只记录 metadata。
        if let Some(ext) = extension.as_deref() {
            if BINARY_EXTENSIONS.contains(&ext) {
                return (
                    FileClassification {
                        kind: FileKind::Binary,
                        confidence: Confidence::High,
                        reason: format!("binary file type (.{ext})"),
                    },
                    false,
                    Some("binary".to_string()),
                );
            }
            if ASSET_EXTENSIONS.contains(&ext) {
                return (
                    FileClassification {
                        kind: FileKind::Asset,
                        confidence: Confidence::High,
                        reason: format!("media/asset file type (.{ext})"),
                    },
                    false,
                    Some("asset".to_string()),
                );
            }
        }

        // 2) 测试：目录段或命名约定。
        if is_test_path(relative_path, &lower_name) {
            return (
                FileClassification {
                    kind: FileKind::Test,
                    confidence: Confidence::High,
                    reason: "test directory or naming convention".to_string(),
                },
                true,
                None,
            );
        }

        // 3) 生成内容目录。
        if is_generated_path(relative_path) {
            return (
                FileClassification {
                    kind: FileKind::Generated,
                    confidence: Confidence::Medium,
                    reason: "default generated directory".to_string(),
                },
                true,
                None,
            );
        }

        // 4) 文档（先于已知配置：README.md 归 Documentation 而非 Config，纲领 §61/§63）。
        let is_documentation = DOCUMENTATION_NAMES.contains(&lower_name.as_str())
            || extension
                .as_deref()
                .is_some_and(|ext| DOCUMENTATION_EXTENSIONS.contains(&ext));
        if is_documentation {
            return (
                FileClassification {
                    kind: FileKind::Documentation,
                    confidence: Confidence::Medium,
                    reason: "documentation extension or well-known name".to_string(),
                },
                true,
                None,
            );
        }

        // 5) 已知配置文件名。
        if known_configuration(file_name).is_some() {
            return (
                FileClassification {
                    kind: FileKind::Config,
                    confidence: Confidence::High,
                    reason: "known configuration file".to_string(),
                },
                true,
                None,
            );
        }

        // 6) 配置风格扩展名（保守兜底）。
        if extension
            .as_deref()
            .is_some_and(|ext| CONFIG_STYLE_EXTENSIONS.contains(&ext))
        {
            return (
                FileClassification {
                    kind: FileKind::Config,
                    confidence: Confidence::Low,
                    reason: format!(
                        "configuration-style extension (.{})",
                        extension.unwrap_or_default()
                    ),
                },
                true,
                None,
            );
        }

        // 7) 已知语言源码。
        if let Some(language) = self.detect_language(file_name) {
            return (
                FileClassification {
                    kind: FileKind::Source,
                    confidence: Confidence::High,
                    reason: format!("{} source extension", language.display_name()),
                },
                true,
                None,
            );
        }

        // 8) 未知：允许存在，不是错误（纲领 §21）。
        (
            FileClassification {
                kind: FileKind::Unknown,
                confidence: Confidence::Low,
                reason: "no known pattern".to_string(),
            },
            true,
            None,
        )
    }
}

impl Default for FileClassifier {
    fn default() -> Self {
        Self::new()
    }
}

fn is_test_path(relative_path: &str, lower_name: &str) -> bool {
    let segments = relative_path.split('/');
    if segments
        .clone()
        .any(|segment| TEST_DIRECTORY_SEGMENTS.contains(&segment))
    {
        return true;
    }
    // *.test.* / *.spec.*（纲领 §23）
    lower_name.contains(".test.") || lower_name.contains(".spec.")
}

fn is_generated_path(relative_path: &str) -> bool {
    relative_path
        .split('/')
        .any(|segment| GENERATED_DIRECTORY_SEGMENTS.contains(&segment))
}

/// 组装 FileInfo 的便捷入口（scanner 使用）。
pub fn build_file_info(
    classifier: &FileClassifier,
    relative_path: &str,
    file_name: String,
    size_bytes: u64,
    modified_at: Option<Timestamp>,
    is_hidden: bool,
    is_symlink: bool,
    max_file_size: u64,
) -> PrismResult<FileInfo> {
    let (classification, mut analyzable, mut non_analyzable_reason) =
        classifier.assess(relative_path, &file_name, is_symlink);
    let language = classifier.detect_language(&file_name);

    // 超大文件：discovered = true, analyzable = false, reason = too_large（纲领 §59）。
    if analyzable && size_bytes > max_file_size {
        analyzable = false;
        non_analyzable_reason = Some("too_large".to_string());
    }

    let extension = Path::new(&file_name)
        .extension()
        .map(|e| e.to_string_lossy().to_ascii_lowercase());

    Ok(FileInfo {
        id: FileId::from_string(format!("file:{relative_path}")),
        relative_path: relative_path.to_string(),
        file_name,
        extension,
        size_bytes,
        language,
        classification,
        analyzable,
        non_analyzable_reason,
        modified_at,
        is_hidden,
        is_symlink,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn classify(path: &str, name: &str) -> (FileKind, String) {
        let classifier = FileClassifier::new();
        let (classification, _, _) = classifier.assess(path, name, false);
        (classification.kind, classification.reason)
    }

    #[test]
    fn classifies_source_by_language_extension() {
        let (kind, reason) = classify("src/main.ts", "main.ts");
        assert_eq!(kind, FileKind::Source);
        assert!(reason.contains("TypeScript"));
    }

    #[test]
    fn separates_language_from_kind() {
        // package.json：JSON 语言 + Config 类型（纲领 §61）。
        let classifier = FileClassifier::new();
        let (classification, analyzable, _) =
            classifier.assess("package.json", "package.json", false);
        assert_eq!(classification.kind, FileKind::Config);
        assert_eq!(
            classifier.detect_language("package.json"),
            Some(Language::Json)
        );

        // foo.test.ts：TypeScript + Test。
        let (classification, _, _) = classifier.assess("src/foo.test.ts", "foo.test.ts", false);
        assert_eq!(classification.kind, FileKind::Test);

        // README.md：Markdown + Documentation。
        let (kind, _) = classify("README.md", "README.md");
        assert_eq!(kind, FileKind::Documentation);
        assert!(analyzable);
    }

    #[test]
    fn test_directory_marks_children_as_test() {
        let (kind, _) = classify("tests/utils.ts", "utils.ts");
        assert_eq!(kind, FileKind::Test);
        let (kind, _) = classify("src/__tests__/app.spec.tsx", "app.spec.tsx");
        assert_eq!(kind, FileKind::Test);
    }

    #[test]
    fn binary_and_asset_files_record_metadata_only() {
        let classifier = FileClassifier::new();
        let (classification, analyzable, reason) =
            classifier.assess("dist/app.dll", "app.dll", false);
        assert_eq!(classification.kind, FileKind::Binary);
        assert!(!analyzable);
        assert_eq!(reason.as_deref(), Some("binary"));

        let (classification, analyzable, reason) =
            classifier.assess("assets/logo.png", "logo.png", false);
        assert_eq!(classification.kind, FileKind::Asset);
        assert!(!analyzable);
        assert_eq!(reason.as_deref(), Some("asset"));
    }

    #[test]
    fn oversized_file_is_discovered_but_not_analyzable() {
        let classifier = FileClassifier::new();
        let info = build_file_info(
            &classifier,
            "src/huge.rs",
            "huge.rs".to_string(),
            4096,
            None,
            false,
            false,
            1024,
        )
        .unwrap();
        // 文件仍出现在结果中，只是不可分析（纲领 §59）。
        assert_eq!(info.classification.kind, FileKind::Source);
        assert!(!info.analyzable);
        assert_eq!(info.non_analyzable_reason.as_deref(), Some("too_large"));
    }

    #[test]
    fn unknown_files_are_allowed() {
        for name in [
            "Dockerfile",
            "Makefile",
            "LICENSE",
            ".editorconfig",
            "data.weird",
        ] {
            let (kind, _) = classify(name, name);
            // LICENSE 命中文档名；其余可为 Unknown，但都不能是错误。
            assert!(matches!(
                kind,
                FileKind::Unknown | FileKind::Documentation | FileKind::Config
            ));
        }
    }

    #[test]
    fn deterministic_file_ids() {
        let classifier = FileClassifier::new();
        let a = build_file_info(
            &classifier,
            "src/a.ts",
            "a.ts".to_string(),
            1,
            None,
            false,
            false,
            1024,
        )
        .unwrap();
        let b = build_file_info(
            &classifier,
            "src/a.ts",
            "a.ts".to_string(),
            1,
            None,
            false,
            false,
            1024,
        )
        .unwrap();
        assert_eq!(a.id, b.id);
        assert_eq!(a.id.as_str(), "file:src/a.ts");
    }

    #[test]
    fn symlink_entries_are_not_analyzable() {
        let classifier = FileClassifier::new();
        let (classification, analyzable, reason) = classifier.assess("link", "link", true);
        assert_eq!(classification.kind, FileKind::Unknown);
        assert!(!analyzable);
        assert_eq!(reason.as_deref(), Some("symlink"));
    }
}
